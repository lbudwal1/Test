// ─── Render a step template in the given language ─────────────────────────────
export function renderStep(templateKey, rawParams, lang) {
  const templates = NAV_STEP_TEMPLATES[lang] || NAV_STEP_TEMPLATES.en;
  const fn = templates[templateKey] || (NAV_STEP_TEMPLATES.en[templateKey]);
  if (!fn) return templateKey;

  // Translate any param that is a location key
  const translatedParams = {};
  for (const [k, v] of Object.entries(rawParams || {})) {
    translatedParams[k] = v; // pass through — caller should pre-translate loc names
  }
  return fn(translatedParams);
}

// Translate a location key to a display name in the given language
export function locName(key, lang) {
  const entry = LOC_NAMES[key];
  if (!entry) return key;
  return entry[lang] || entry.en;
}
